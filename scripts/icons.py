#!/usr/bin/env python3
"""Item icons for the armoury and HUD.

  python3 scripts/icons.py add <image.png> <id>   import upscaled pixel art as icon <id>, then rebuild
  python3 scripts/icons.py build                  regenerate src/icons.ts from art/icons/*.png

<id> is the WEAPONS or GEAR key in src/game1.js (e.g. silenced, flamer, deck2).
Source art may be drawn at any whole-number scale on a transparent background (512x256 at 4x works
well); it is sampled back to its native pixels, cropped, padded to the 96:44 icon shape and reduced to
24 colours. Needs Pillow.
"""
import base64, json, sys
from collections import Counter
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
ICONS = ROOT / 'art' / 'icons'
OUT = ROOT / 'src' / 'icons.ts'


def pixel_scale(im):
    runs = Counter()
    w, h = im.size
    for y in range(0, h, 3):
        prev, n = None, 0
        for x in range(w):
            p = im.getpixel((x, y))
            if p == prev:
                n += 1
            else:
                if prev is not None and prev[3]:
                    runs[n] += 1
                prev, n = p, 1
    total = sum(runs.values()) or 1
    return min((r for r, c in runs.items() if c / total > 0.05), default=1)


def add(path, ident):
    im = Image.open(path).convert('RGBA')
    s = pixel_scale(im)
    w, h = im.size[0] // s, im.size[1] // s
    nat = Image.new('RGBA', (w, h))
    for y in range(h):
        for x in range(w):
            p = im.getpixel((x * s + s // 2, y * s + s // 2))
            nat.putpixel((x, y), p if p[3] >= 128 else (0, 0, 0, 0))
    nat = nat.crop(nat.getbbox())
    w, h = nat.size
    cw = w + 4
    ch = max(h + 2, round(cw * 44 / 96))
    cv = Image.new('RGBA', (cw, ch))
    cv.paste(nat, ((cw - w) // 2, (ch - h) // 2))
    q = cv.quantize(colors=24, method=Image.Quantize.FASTOCTREE).convert('RGBA')
    out = Image.new('RGBA', cv.size)
    for y in range(ch):
        for x in range(cw):
            if cv.getpixel((x, y))[3]:
                out.putpixel((x, y), q.getpixel((x, y))[:3] + (255,))
    ICONS.mkdir(parents=True, exist_ok=True)
    out.save(ICONS / f'{ident}.png', optimize=True)
    print(f'{ident}: {s}x art, {w}x{h} native pixels, saved art/icons/{ident}.png')


def build():
    data = {p.stem: base64.b64encode(p.read_bytes()).decode() for p in sorted(ICONS.glob('*.png'))}
    OUT.write_text('/* ================================================================ item icon images\n'
                   '   Generated by scripts/icons.py from art/icons/*.png. Do not edit by hand. */\n'
                   'export const ICON_IMG = ' + json.dumps(data) + ';\n')
    print(f'src/icons.ts: {len(data)} icons')


if __name__ == '__main__':
    a = sys.argv[1:]
    if a[:1] == ['add'] and len(a) == 3:
        add(a[1], a[2]); build()
    elif a == ['build']:
        build()
    else:
        print(__doc__); sys.exit(2)
